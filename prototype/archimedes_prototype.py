#!/usr/bin/env python3
"""
PROJECT ARCHIMEDES - prototype

A small, fully reproducible "hypothesis -> analysis -> critique" loop on
synthetic microbial growth curves.

What this is: five rule-based roles (Knowledge, HypothesisGenerator, Analyst,
Critic, Orchestrator) that pass structured records to each other. No language
model is called; each role is deterministic code, so every verdict can be
traced to a number.

What this is not: a discovery engine. The data are generated by this script
from a logistic model, so the "findings" only show that the pipeline recovers
effects that were planted, and rejects one that was not.
"""

from __future__ import annotations

import argparse
import hashlib
import json
from dataclasses import asdict, dataclass, field
from pathlib import Path
from typing import Dict, List, Optional

import numpy as np
import pandas as pd
from scipy import stats
from scipy.optimize import curve_fit

A0 = 0.01  # inoculum OD600, fixed in both the generator and the fit
ALPHA = 0.05
MIN_R2 = 0.98
PLATEAU_FRACTION = 0.8  # a curve "reached plateau" if its last readings are at least this share of fitted K

TRUE_PARAMS: Dict[str, Dict[str, float]] = {
    "M9_glucose": {"K": 1.2, "r": 0.45, "t0": 2.0},
    "M9_glycerol": {"K": 0.9, "r": 0.32, "t0": 3.5},
    "LB": {"K": 1.8, "r": 0.65, "t0": 1.5},
    "M9_glucose_lowN": {"K": 0.7, "r": 0.28, "t0": 4.0},
    "M9_acetate": {"K": 0.6, "r": 0.22, "t0": 5.0},
}


def logistic_growth(t, K, r, t0):
    """Logistic curve shifted by a lag t0. OD(t0) == A0."""
    return K / (1 + (K / A0 - 1) * np.exp(-r * (t - t0)))


# ---------------------------------------------------------------- data


def generate_synthetic_growth_data(n_reps: int = 4, n_timepoints: int = 48, seed: int = 42, hours: float = 24.0):
    """Return (curves, truth). `truth` holds the parameters each replicate was drawn with."""
    rng = np.random.default_rng(seed)
    t = np.linspace(0, hours, n_timepoints)
    rows, truth = [], []
    for cond, p in TRUE_PARAMS.items():
        for rep in range(n_reps):
            K = p["K"] * (1 + rng.normal(0, 0.05))
            r = p["r"] * (1 + rng.normal(0, 0.08))
            t0 = p["t0"] + rng.normal(0, 0.3)
            od = logistic_growth(t, K, r, t0) + rng.normal(0, 0.03, n_timepoints)
            od = np.clip(od, 0.001, None)
            truth.append({"condition": cond, "replicate": rep, "K": K, "r": r, "t0": t0})
            for ti, odi in zip(t, od):
                rows.append(
                    {
                        "condition": cond,
                        "replicate": rep,
                        "time_h": round(float(ti), 3),
                        "od600": round(float(odi), 4),
                    }
                )
    return pd.DataFrame(rows), pd.DataFrame(truth)


def data_hash(df: pd.DataFrame) -> str:
    return hashlib.sha256(df.to_csv(index=False).encode()).hexdigest()


# ---------------------------------------------------------------- records


@dataclass
class Hypothesis:
    id: str
    statement: str
    parameter: str  # K, r or t0
    group_a: str
    group_b: str
    direction: str  # "greater": a > b, "less": a < b
    rationale: str
    falsified_if: str


@dataclass
class TestResult:
    hypothesis_id: str
    mean_a: float
    mean_b: float
    n_a: int
    n_b: int
    t_stat: float
    p_one_sided: float
    p_holm: float
    cohens_d: float
    ci95_diff: List[float]


@dataclass
class Verdict:
    hypothesis_id: str
    verdict: str  # supported | refuted | inconclusive
    objections: List[str] = field(default_factory=list)


# ---------------------------------------------------------------- roles


class KnowledgeAgent:
    """Holds the prior beliefs hypotheses are derived from. Priors, not facts."""

    PRIORS = [
        {"topic": "rich_vs_minimal", "belief": "Rich medium (LB) supports faster growth than minimal medium."},
        {"topic": "nitrogen_limit", "belief": "Nitrogen limitation lowers final biomass."},
        {"topic": "poor_carbon_lag", "belief": "Poor carbon sources such as acetate lengthen the lag phase."},
        {"topic": "glycerol_vs_glucose", "belief": "Glycerol supports slower growth than glucose."},
    ]

    def lookup(self, topic: str) -> str:
        for prior in self.PRIORS:
            if prior["topic"] == topic:
                return prior["belief"]
        raise KeyError(topic)


class HypothesisGenerator:
    """Turns priors into directional, falsifiable comparisons. H5 is a deliberate negative control."""

    def generate(self, knowledge: KnowledgeAgent) -> List[Hypothesis]:
        def crit(param, a, b, word):
            return f"{param}({a}) is not {word} than {param}({b}) at Holm-adjusted p < {ALPHA}"

        return [
            Hypothesis("H1", "LB has a higher growth rate than M9 glucose.", "r", "LB", "M9_glucose", "greater",
                       knowledge.lookup("rich_vs_minimal"), crit("r", "LB", "M9_glucose", "greater")),
            Hypothesis("H2", "Low nitrogen lowers carrying capacity versus M9 glucose.", "K", "M9_glucose_lowN",
                       "M9_glucose", "less", knowledge.lookup("nitrogen_limit"),
                       crit("K", "M9_glucose_lowN", "M9_glucose", "smaller")),
            Hypothesis("H3", "Acetate has a longer lag than M9 glucose.", "t0", "M9_acetate", "M9_glucose", "greater",
                       knowledge.lookup("poor_carbon_lag"), crit("t0", "M9_acetate", "M9_glucose", "greater")),
            Hypothesis("H4", "Glycerol has a lower growth rate than M9 glucose.", "r", "M9_glycerol", "M9_glucose",
                       "less", knowledge.lookup("glycerol_vs_glucose"),
                       crit("r", "M9_glycerol", "M9_glucose", "smaller")),
            Hypothesis("H5", "Negative control: glycerol reaches a higher carrying capacity than LB.", "K",
                       "M9_glycerol", "LB", "greater", "No prior supports this; the pipeline should refute it.",
                       crit("K", "M9_glycerol", "LB", "greater")),
        ]


class Analyst:
    """Fits one logistic curve per replicate, then runs one Welch test per hypothesis."""

    def fit_curves(self, curves: pd.DataFrame) -> pd.DataFrame:
        fits = []
        for (cond, rep), g in curves.groupby(["condition", "replicate"], sort=False):
            t, y = g["time_h"].to_numpy(), g["od600"].to_numpy()
            p0 = [max(y.max(), 0.05), 0.4, 2.0]
            popt, _ = curve_fit(logistic_growth, t, y, p0=p0, bounds=([0.02, 0.01, -5], [5, 3, 20]), maxfev=20000)
            resid = y - logistic_growth(t, *popt)
            ss_tot = float(((y - y.mean()) ** 2).sum())
            r2 = 1 - float((resid**2).sum()) / ss_tot if ss_tot > 0 else 0.0
            plateau = bool(y[-3:].mean() >= PLATEAU_FRACTION * popt[0])
            fits.append({"condition": cond, "replicate": int(rep), "K": popt[0], "r": popt[1], "t0": popt[2],
                         "r2": r2, "plateau": plateau})
        return pd.DataFrame(fits)

    def test(self, hypotheses: List[Hypothesis], fits: pd.DataFrame) -> List[TestResult]:
        raw = []
        for h in hypotheses:
            a = fits.loc[fits["condition"] == h.group_a, h.parameter].to_numpy()
            b = fits.loc[fits["condition"] == h.group_b, h.parameter].to_numpy()
            res = stats.ttest_ind(a, b, equal_var=False, alternative=h.direction)
            va, vb = a.var(ddof=1), b.var(ddof=1)
            pooled = np.sqrt((va + vb) / 2)
            d = float((a.mean() - b.mean()) / pooled) if pooled > 0 else float("inf")
            se = np.sqrt(va / len(a) + vb / len(b))
            dof = (va / len(a) + vb / len(b)) ** 2 / (
                (va / len(a)) ** 2 / (len(a) - 1) + (vb / len(b)) ** 2 / (len(b) - 1)
            )
            half = stats.t.ppf(0.975, dof) * se
            diff = a.mean() - b.mean()
            raw.append((h, a, b, float(res.statistic), float(res.pvalue), d, [float(diff - half), float(diff + half)]))

        adjusted = holm([r[4] for r in raw])
        return [
            TestResult(h.id, float(a.mean()), float(b.mean()), len(a), len(b), t, p, p_adj, d, ci)
            for (h, a, b, t, p, d, ci), p_adj in zip(raw, adjusted)
        ]


def holm(pvalues: List[float]) -> List[float]:
    """Holm step-down adjustment, returned in the input order."""
    order = np.argsort(pvalues)
    m = len(pvalues)
    adjusted = [0.0] * m
    running = 0.0
    for rank, idx in enumerate(order):
        running = max(running, min(1.0, (m - rank) * pvalues[idx]))
        adjusted[idx] = running
    return adjusted


class Critic:
    """Decides each verdict and records every reason to distrust it."""

    def review(self, hypotheses: List[Hypothesis], results: List[TestResult], fits: pd.DataFrame,
               synthetic: bool = True) -> List[Verdict]:
        verdicts = []
        for h, res in zip(hypotheses, results):
            objections = []
            used = fits[fits["condition"].isin([h.group_a, h.group_b])]
            poor = used[used["r2"] < MIN_R2]
            if len(poor):
                objections.append(f"{len(poor)} of {len(used)} curve fits have R2 below {MIN_R2}.")
            unidentified = [
                cond for cond in (h.group_a, h.group_b)
                if (~used.loc[used["condition"] == cond, "plateau"]).mean() > 0.5
            ]
            if unidentified:
                objections.append(
                    f"Curves for {', '.join(unidentified)} did not reach plateau within the run, so K is not "
                    "identifiable and r and lag are biased. Extend the run before testing this."
                )
            if min(res.n_a, res.n_b) < 5:
                objections.append(f"Only {res.n_a} and {res.n_b} replicates; the t-test has little power to detect small effects.")
            if synthetic:
                objections.append("Data are synthetic; this verdict says nothing about real cultures.")
            if h.parameter == "t0":
                objections.append("Lag is defined relative to a fixed inoculum OD; an error in that value shifts every lag.")

            if len(poor) > len(used) / 2 or unidentified:
                verdict = "inconclusive"
            elif res.p_holm < ALPHA:
                verdict = "supported"
            else:
                observed = res.mean_a - res.mean_b
                opposite = observed < 0 if h.direction == "greater" else observed > 0
                verdict = "refuted" if opposite and abs(res.cohens_d) >= 0.8 else "inconclusive"
            verdicts.append(Verdict(h.id, verdict, objections))
        return verdicts


class Orchestrator:
    """Runs the roles in order and keeps a step log."""

    def __init__(self, seed: int = 42, n_reps: int = 4, hours: float = 24.0, n_timepoints: int = 48):
        self.seed, self.n_reps, self.hours, self.n_timepoints = seed, n_reps, hours, n_timepoints
        self.log: List[Dict[str, str]] = []

    def _step(self, role: str, summary: str):
        self.log.append({"step": len(self.log) + 1, "role": role, "summary": summary})

    def run(self) -> Dict:
        curves, truth = generate_synthetic_growth_data(
            n_reps=self.n_reps, n_timepoints=self.n_timepoints, seed=self.seed, hours=self.hours
        )
        digest = data_hash(curves)
        self._step("Orchestrator", f"Generated {len(curves)} readings, sha256 {digest[:12]}.")

        knowledge = KnowledgeAgent()
        hypotheses = HypothesisGenerator().generate(knowledge)
        self._step("HypothesisGenerator", f"Proposed {len(hypotheses)} hypotheses from {len(knowledge.PRIORS)} priors.")

        analyst = Analyst()
        fits = analyst.fit_curves(curves)
        self._step(
            "Analyst",
            f"Fitted {len(fits)} curves, median R2 {fits['r2'].median():.4f}, "
            f"{int((~fits['plateau']).sum())} without plateau.",
        )
        results = analyst.test(hypotheses, fits)
        self._step("Analyst", f"Ran {len(results)} Welch tests with Holm adjustment.")

        verdicts = Critic().review(hypotheses, results, fits)
        counts = pd.Series([v.verdict for v in verdicts]).value_counts().to_dict()
        self._step("Critic", f"Verdicts: {counts}.")

        merged = fits.merge(truth, on=["condition", "replicate"], suffixes=("_fit", "_true"))
        recovery = {
            p: round(float(((merged[f"{p}_fit"] - merged[f"{p}_true"]).abs() / merged[f"{p}_true"].abs()).median()), 4)
            for p in ("K", "r", "t0")
        }

        return {
            "meta": {
                "seed": self.seed,
                "n_conditions": len(TRUE_PARAMS),
                "n_replicates": self.n_reps,
                "run_hours": self.hours,
                "n_timepoints": self.n_timepoints,
                "data_sha256": digest,
                "synthetic": True,
                "alpha": ALPHA,
            },
            "fit_quality": {
                "median_r2": round(float(fits["r2"].median()), 4),
                "min_r2": round(float(fits["r2"].min()), 4),
                "curves_without_plateau": {
                    cond: int((~g["plateau"]).sum()) for cond, g in fits.groupby("condition", sort=False)
                },
                "median_relative_error_vs_truth": recovery,
            },
            "condition_means": {
                cond: {p: round(float(g[p].mean()), 4) for p in ("K", "r", "t0")}
                for cond, g in fits.groupby("condition", sort=False)
            },
            "hypotheses": [
                {**asdict(h), "test": _rounded(asdict(r)), "verdict": v.verdict, "objections": v.objections}
                for h, r, v in zip(hypotheses, results, verdicts)
            ],
            "log": self.log,
        }


def _rounded(d: Dict) -> Dict:
    out = {}
    for k, v in d.items():
        if isinstance(v, float):
            out[k] = float(f"{v:.4g}")
        elif isinstance(v, list):
            out[k] = [float(f"{x:.4g}") for x in v]
        else:
            out[k] = v
    return out


def main(argv: Optional[List[str]] = None) -> Dict:
    parser = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    parser.add_argument("--seed", type=int, default=42)
    parser.add_argument("--reps", type=int, default=4)
    parser.add_argument("--hours", type=float, default=24.0, help="length of each simulated run")
    parser.add_argument("--timepoints", type=int, default=48, help="readings per curve")
    parser.add_argument("--out", type=Path, default=Path(__file__).with_name("run_result.json"))
    args = parser.parse_args(argv)

    result = Orchestrator(seed=args.seed, n_reps=args.reps, hours=args.hours, n_timepoints=args.timepoints).run()
    args.out.write_text(json.dumps(result, indent=2, ensure_ascii=False) + "\n", encoding="utf-8")

    for entry in result["log"]:
        print(f"[{entry['step']}] {entry['role']}: {entry['summary']}")
    for h in result["hypotheses"]:
        print(f"{h['id']} {h['verdict']:<12} p_holm={h['test']['p_holm']:<10} {h['statement']}")
    print(f"Wrote {args.out}")
    return result


if __name__ == "__main__":
    main()
